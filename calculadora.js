function somar(a, b) {   
    // Retorna o resultado da adição matemática de 'a' mais 'b'
    return a + b;
}
function subtrair(a, b) {
    // Retorna o resultado da subtração de 'a' menos 'b'
    return a - b;
}

function multiplicar(a, b) {
    // Retorna o resultado da multiplicação de 'a' vezes 'b'
    return a * b;
}
console.log("A soma de 5 e 3 é:", somar(5, 3));
